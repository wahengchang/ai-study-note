// ---------------------------------------------------------------------------
// 輸出 PNG 的獨立驗證：signature、chunk 順序與 CRC、IHDR、IDAT 列長度與 filter
// ---------------------------------------------------------------------------

const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let index = 0; index < 256; index += 1) {
    let value = index;
    for (let bit = 0; bit < 8; bit += 1) value = (value & 1) !== 0 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
    table[index] = value >>> 0;
  }
  return table;
})();

function crc32(bytes: Uint8Array): number {
  let value = 0xffffffff;
  for (let index = 0; index < bytes.length; index += 1) value = CRC_TABLE[(value ^ bytes[index]!) & 0xff]! ^ (value >>> 8);
  return (value ^ 0xffffffff) >>> 0;
}

type PngRaster = Readonly<{
  width: number;
  height: number;
  colorType: number;
  bitDepth: number;
  interlace: number;
  pixels: Uint8Array;
  channels: 3 | 4;
}>;

function parsePng(bytes: Uint8Array): PngRaster {
  const view = Buffer.from(bytes);
  assert.deepEqual([...view.subarray(0, 8)], [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a], "PNG signature");
  const types: string[] = [];
  const idat: Uint8Array[] = [];
  let header: { width: number; height: number; bitDepth: number; colorType: number; interlace: number } | undefined;
  let offset = 8;
  while (offset + 12 <= view.length) {
    const length = view.readUInt32BE(offset);
    const type = view.toString("latin1", offset + 4, offset + 8);
    const data = view.subarray(offset + 8, offset + 8 + length);
    types.push(type);
    assert.equal(view.readUInt32BE(offset + 8 + length), crc32(view.subarray(offset + 4, offset + 8 + length)), `${type} CRC`);
    if (type === "IHDR") {
      header = {
        width: data.readUInt32BE(0),
        height: data.readUInt32BE(4),
        bitDepth: data[8]!,
        colorType: data[9]!,
        interlace: data[12]!,
      };
      assert.equal(data[10], 0, "compression method");
      assert.equal(data[11], 0, "filter method");
    }
    if (type === "IDAT") idat.push(new Uint8Array(data));
    offset += 12 + length;
  }
  assert.equal(offset, view.length, "chunk 串必須完整結束於 IEND");
  assert.deepEqual(types, ["IHDR", "IDAT", "IEND"]);
  const raster = header!;
  assert.equal(raster.bitDepth, 8, "輸出必須是 8-bit");
  assert.equal(raster.interlace, 0, "輸出必須是非交錯");
  assert.ok(raster.colorType === 2 || raster.colorType === 6, "輸出必須是 RGB 或 RGBA");
  const channels: 3 | 4 = raster.colorType === 6 ? 4 : 3;
  const stride = raster.width * channels;
  const raw = Uint8Array.from(inflateSync(Buffer.concat(idat.map((chunk) => Buffer.from(chunk)))));
  assert.equal(raw.length, raster.height * (stride + 1), "IDAT 長度必須等於列數 × (1 + 列 bytes)");
  const pixels = new Uint8Array(raster.width * raster.height * channels);
  for (let y = 0; y < raster.height; y += 1) {
    assert.equal(raw[y * (stride + 1)], 0, "輸出必須只使用 filter type 0");
    pixels.set(raw.subarray(y * (stride + 1) + 1, y * (stride + 1) + 1 + stride), y * stride);
  }
  return { ...raster, pixels, channels };
}

function pixelAt(raster: PngRaster, x: number, y: number): number[] {
  const base = (y * raster.width + x) * raster.channels;
  return [...raster.pixels.subarray(base, base + raster.channels)];
}

/** 測試自建的 PNG chunk（含正確 CRC），用來驗證輔助 chunk 與未知 critical chunk 的處理。 */
function pngChunk(type: string, data: Buffer): Buffer {
  const body = Buffer.concat([Buffer.from(type, "latin1"), data]);
  const chunk = Buffer.allocUnsafe(body.length + 8);
  chunk.writeUInt32BE(data.length, 0);
  chunk.set(body, 4);
  chunk.writeUInt32BE(crc32(body), body.length + 4);
  return chunk;
}

